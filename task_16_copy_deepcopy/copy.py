"""
1. 不可变对象，拷贝没意义（浅拷贝和深拷贝效果一样）
2. 元组里有嵌套列表——浅拷贝不会拷贝但是深拷贝可以
3. 文件对象、数据库连接——不能拷贝
"""
# 浅拷贝：
# 外层列表——复制了（地址不同）
# 内层元素——共享（地址相同）
#
# 深拷贝：
# 外层列表——复制了（地址不同）
# 内层元素——也复制了（地址也不同）
# 如果列表里只有数字、字符串这种简单元素，浅拷贝和深拷贝效果一样，因为没有内层嵌套。只有列表里面还有列表（或字典等）时，才会有区别。
list1 = [1,2,3,[4,5,6]]
list2 = list1.copy()
list2[3].append(7)
print(id(list1),id(list1[0]), id(list1[1]), id(list1[2]), id(list1[3]), list1)
print(id(list2),id(list2[0]), id(list2[1]), id(list2[2]), id(list2[3]), list2)
# 深拷贝
# 先append再深拷贝
# list1 添加400 → list1=[...[400]]
# 深拷贝        → list2=[...[400]]  ← 400也在
# 之后互不影响
#
# # 先深拷贝再append（你课程里的写法）
# 深拷贝        → list2=[...[]]    ← 没有400
# list1 添加400 → list1=[...[400]]
# list2不受影响 → list2=[...[]]    ← 还是没有400
# 深拷贝是拷贝那一刻的快照，拷贝之前的改动会被一起复制进去，拷贝之后的改动才互不影响。
import copy

list1 = [1, 2, 3, [100, 200, 300]]
list1[3].append(100000000)       # 先给list1添加400
list2 = copy.deepcopy(list1)  # 再深拷贝
list1[3].append(9999999)

print(list1)  # [1, 2, 3, [100, 200, 300, 400]]
print(list2)  # [1, 2, 3, [100, 200, 300, 400]]  ← 400也被拷贝进去了